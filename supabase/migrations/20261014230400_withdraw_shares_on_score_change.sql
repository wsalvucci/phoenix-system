-- Automatic share withdrawal when a score changes (DATA_DISCLOSURE.md §10.3 violation 4, D3).
-- Additive: one table, one trigger function, one trigger, one RPC.
--
-- A share is a live join to student_point. If a teacher corrects a 90 to a 40 after the child shared
-- it, the group would see 40. The child agreed to show a 90. The ruling prefers withdrawal over a
-- snapshot, because a snapshot would keep publishing a number the teacher has said is wrong.
--
-- Mechanism: an AFTER UPDATE trigger on student_point. It fires on every write path at once:
-- edit_scorebook_point_event, bulk entry, CSV import, TA upserts, and any future path. When
-- point_value actually changes (IS DISTINCT FROM, so an upsert that rewrites the same value does
-- nothing), it deletes that student_point's shared_point rows and records one withdrawal notice for
-- the sharer. The sharer is told on their next visit ("Your shared score for Quiz 4 changed, so it is
-- no longer shared"), and the notice is marked seen.
--
-- Data note: existing shares are untouched by this migration. From now on a score change removes the
-- shared_point rows for that score. That is the ruled behaviour (D3), and the student can share again.
-- input_score-only changes do not withdraw, because recipients never see the input score (§10.3).

create table public.shared_point_withdrawal (
  id bigint generated by default as identity primary key,
  student_point_id bigint not null references public.student_point (id) on update cascade on delete cascade,
  student_id bigint not null references public.student (id) on update cascade on delete cascade,
  withdrawn_at timestamptz not null default now(),
  seen_at timestamptz
);

-- Serves the sharer's "unseen notices" read (student_id, seen_at is null).
create index shared_point_withdrawal_unseen_idx
  on public.shared_point_withdrawal (student_id) where seen_at is null;
-- Serves the FK cascade from student_point.
create index shared_point_withdrawal_student_point_id_idx
  on public.shared_point_withdrawal (student_point_id);
-- The trigger deletes shared_point by student_point_id. The table has no index on it.
create index if not exists shared_point_student_point_id_idx on public.shared_point (student_point_id);

alter table public.shared_point_withdrawal enable row level security;
revoke all on table public.shared_point_withdrawal from anon, authenticated;
grant all on table public.shared_point_withdrawal to service_role;

create or replace function public.withdraw_shares_on_score_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  _removed integer;
begin
  delete from public.shared_point sp where sp.student_point_id = new.id;
  get diagnostics _removed = row_count;
  if _removed > 0 then
    insert into public.shared_point_withdrawal (student_point_id, student_id)
    values (new.id, new.student_id);
  end if;
  return null;
end;
$$;

revoke all on function public.withdraw_shares_on_score_change() from public, anon, authenticated;

create trigger student_point_withdraw_shares
  after update of point_value on public.student_point
  for each row
  when (old.point_value is distinct from new.point_value)
  execute function public.withdraw_shares_on_score_change();

-- Sharer's notices: returns the unseen ones and marks them seen in the same call. The event name is
-- the sharer's own data. Service_role only; the actor must be the student's own account (not a
-- parent, since sharing is student-only, §10.3).
create or replace function public.take_share_withdrawal_notices(p_actor_user_id bigint)
returns table (withdrawn_at timestamptz, event_name text, event_date timestamptz)
language plpgsql
volatile
security definer
set search_path = ''
as $$
#variable_conflict use_column
begin
  return query
  with mine as (
    select s.id from public.student s where s."linkedUser" = p_actor_user_id
  ),
  taken as (
    update public.shared_point_withdrawal w
    set seen_at = now()
    where w.seen_at is null and w.student_id in (select m.id from mine m)
    returning w.student_point_id, w.withdrawn_at
  )
  select t.withdrawn_at, coalesce(pe.name, pt.name::text), pe.date
  from taken t
  join public.student_point sp on sp.id = t.student_point_id
  join public.point_event pe on pe.id = sp.point_event_id
  left join public.point_template pt on pt.id = pe.template_id
  order by t.withdrawn_at desc;
end;
$$;

revoke all on function public.take_share_withdrawal_notices(bigint) from public, anon, authenticated;
grant execute on function public.take_share_withdrawal_notices(bigint) to service_role;
