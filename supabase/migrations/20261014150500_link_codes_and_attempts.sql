-- Link codes: CSPRNG generator, rate-limited redemption with uniform failure, a name preview, and
-- admin-visible, revocable parent links (DATA_DISCLOSURE.md §10.4, §10.11, D11, D12).
-- Additive. No existing code changes here. The one-time regeneration of existing codes and the
-- UNIQUE (school_id, link_code) constraint are in 20261014150700, which is flagged separately.
--
-- Contract (BACKEND_PLAN.md section 6):
--   generate_link_code()   10 Crockford base-32 characters = 50 bits (pgcrypto CSPRNG). New default
--                          for student.link_code and teacher.link_code. Affects new rows only.
--   redeem_link_code(...)  'linked' | 'no_match' | 'rate_limited'. One atomic call that checks the
--                          bucket, matches the code to the school, links, and records failures.
--                          Wrong code, wrong school and already linked are all 'no_match'.
--   preview_link_code(...) first name and last initial for the "Is this Maya R.?" step, same bucket.
--                          It refuses legacy 7-character codes, so the preview cannot work until the
--                          codes have been regenerated (D12: not built until codes are >= 40 bits).
--   admin_* functions      list and revoke parent links, and rotate a code. Admin of the school only.
-- Rate limit (proposed, BACKEND_PLAN.md decision L-2): 5 failures per user per hour, 20 per client key
-- per hour. Lookup and link share the bucket. Failures are logged WITHOUT the code. The client key is
-- an HMAC of the client IP, computed by the server with a server-only secret, never the raw IP.
-- Rows older than 24 hours are purged on every call.

create or replace function public.generate_link_code()
returns text
language sql
volatile
set search_path = ''
as $$
  select public.random_crockford(10);
$$;

alter table public.student alter column link_code set default public.generate_link_code();
alter table public.teacher alter column link_code set default public.generate_link_code();

-- Crockford normalisation: case-insensitive, ignores spaces and hyphens, I/L -> 1, O -> 0.
-- Legacy hex codes contain none of I, L, O, so upper() alone matches them.
create or replace function public.normalize_link_code(p_code text)
returns text
language sql
immutable
set search_path = ''
as $$
  select translate(upper(regexp_replace(coalesce(p_code, ''), '[\s-]', '', 'g')), 'ILO', '110');
$$;

create table public.link_attempt (
  id bigint generated by default as identity primary key,
  user_id bigint references public."user" (id) on update cascade on delete cascade,
  client_key text check (client_key is null or char_length(client_key) between 16 and 128),
  purpose text not null check (purpose in ('student_claim', 'parent_link', 'teacher_claim', 'preview')),
  attempted_at timestamptz not null default now()
);
-- Serve the two bucket counts and the 24-hour purge.
create index link_attempt_user_time_idx on public.link_attempt (user_id, attempted_at);
create index link_attempt_client_time_idx on public.link_attempt (client_key, attempted_at);
create index link_attempt_time_idx on public.link_attempt (attempted_at);

alter table public.link_attempt enable row level security;
revoke all on table public.link_attempt from anon, authenticated;
grant all on table public.link_attempt to service_role;

-- Audit of admin revocations (who removed which parent link, and when). There is no other trace,
-- because revoking deletes the user_student_pair row.
create table public.parent_link_revocation (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.student (id) on update cascade on delete cascade,
  parent_user_id bigint references public."user" (id) on update cascade on delete set null,
  linked_at timestamptz,
  revoked_by_user_id bigint references public."user" (id) on update cascade on delete set null,
  revoked_at timestamptz not null default now()
);
create index parent_link_revocation_student_id_idx on public.parent_link_revocation (student_id);
alter table public.parent_link_revocation enable row level security;
revoke all on table public.parent_link_revocation from anon, authenticated;
grant all on table public.parent_link_revocation to service_role;

-- Internal: purge, then report whether the caller is over the limit. Takes a per-user transaction lock
-- so two parallel attempts cannot both slip under it.
create or replace function public.link_attempt_blocked(p_user_id bigint, p_client_key text)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('link_attempt:' || coalesce(p_user_id, -1)::text, 0));
  delete from public.link_attempt a where a.attempted_at < now() - interval '24 hours';
  return (
      select count(*) from public.link_attempt a
      where a.user_id = p_user_id and a.attempted_at > now() - interval '1 hour'
    ) >= 5
    or (
      p_client_key is not null and (
        select count(*) from public.link_attempt a
        where a.client_key = p_client_key and a.attempted_at > now() - interval '1 hour'
      ) >= 20
    );
end;
$$;

create or replace function public.redeem_link_code(
  p_actor_user_id bigint,
  p_school_id bigint,
  p_code text,
  p_purpose text,
  p_client_key text
)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  _code text := public.normalize_link_code(p_code);
  _student_id bigint;
  _teacher_id bigint;
  _n bigint;
  _done boolean := false;
begin
  if p_purpose not in ('student_claim', 'parent_link', 'teacher_claim') then
    raise exception 'Unknown purpose' using errcode = '22023';
  end if;
  if p_actor_user_id is null or not exists (select 1 from public."user" u where u.id = p_actor_user_id) then
    return 'no_match';
  end if;
  if public.link_attempt_blocked(p_actor_user_id, p_client_key) then
    return 'rate_limited';
  end if;

  -- Exactly one match is required. Until 20261014150700 adds uniqueness, legacy 28-bit codes can
  -- collide within a school, and an ambiguous code must never pick a child.
  if _code <> '' and p_school_id is not null then
    if p_purpose in ('student_claim', 'parent_link') then
      select min(s.id), count(*) into _student_id, _n
      from public.student s
      where s.school_id = p_school_id and upper(s.link_code) = _code;
      if _n = 1 then
        if p_purpose = 'student_claim' then
          update public.student s set "linkedUser" = p_actor_user_id
          where s.id = _student_id and s."linkedUser" is null;
          _done := found;
        else
          insert into public.user_student_pair (user_id, student_id)
          values (p_actor_user_id, _student_id)
          on conflict do nothing;
          _done := found;
        end if;
      end if;
    else
      select min(t.id), count(*) into _teacher_id, _n
      from public.teacher t
      where t.school_id = p_school_id and upper(t.link_code) = _code;
      if _n = 1 then
        update public.teacher t set linked_user = p_actor_user_id
        where t.id = _teacher_id and t.linked_user is null;
        _done := found;
      end if;
    end if;
  end if;

  if _done then
    return 'linked';
  end if;
  insert into public.link_attempt (user_id, client_key, purpose)
  values (p_actor_user_id, p_client_key, p_purpose);
  return 'no_match';
end;
$$;

-- Status is 'match' | 'no_match' | 'rate_limited'. Names are null unless status = 'match'. Student and
-- parent purposes only (§10.4 condition 6). Returns no id: the commit call re-submits school and code.
create or replace function public.preview_link_code(
  p_actor_user_id bigint,
  p_school_id bigint,
  p_code text,
  p_purpose text,
  p_client_key text
)
returns table (status text, first_name text, last_initial text)
language plpgsql
volatile
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  _code text := public.normalize_link_code(p_code);
  _first text;
  _last text;
  _n bigint;
begin
  if p_purpose not in ('student_claim', 'parent_link') then
    raise exception 'Unknown purpose' using errcode = '22023';
  end if;
  if p_actor_user_id is null or not exists (select 1 from public."user" u where u.id = p_actor_user_id) then
    return query select 'no_match'::text, null::text, null::text;
    return;
  end if;
  if public.link_attempt_blocked(p_actor_user_id, p_client_key) then
    return query select 'rate_limited'::text, null::text, null::text;
    return;
  end if;

  if char_length(_code) = 10 and p_school_id is not null then
    select min(s.first_name), min(s.last_name), count(*) into _first, _last, _n
    from public.student s
    where s.school_id = p_school_id
      and upper(s.link_code) = _code
      and (p_purpose = 'parent_link' or s."linkedUser" is null);
    if _n <> 1 then
      _first := null;
    end if;
  end if;

  if _first is null then
    insert into public.link_attempt (user_id, client_key, purpose)
    values (p_actor_user_id, p_client_key, 'preview');
    return query select 'no_match'::text, null::text, null::text;
    return;
  end if;
  return query select 'match'::text, _first, upper(left(btrim(_last), 1));
end;
$$;

-- Admin: parent links on one student (§10.4 "parent links must be listed on the student's record").
create or replace function public.admin_list_parent_links(p_actor_user_id bigint, p_student_id bigint)
returns table (parent_user_id bigint, linked_at timestamptz, parent_name text, parent_email text)
language sql
stable
security definer
set search_path = ''
as $$
  select usp.user_id, usp.created_at,
    nullif(btrim(coalesce(u.first_name, '') || ' ' || coalesce(u.last_name, '')), ''),
    au.email::text
  from public.user_student_pair usp
  join public.student s on s.id = usp.student_id
  join public."user" u on u.id = usp.user_id
  left join auth.users au on au.id = u.supabase_id
  where usp.student_id = p_student_id
    and public.is_admin_of_school(p_actor_user_id, s.school_id)
  order by usp.created_at;
$$;

create or replace function public.admin_revoke_parent_link(
  p_actor_user_id bigint,
  p_student_id bigint,
  p_parent_user_id bigint
)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  _linked_at timestamptz;
begin
  if not exists (
    select 1 from public.student s
    where s.id = p_student_id and public.is_admin_of_school(p_actor_user_id, s.school_id)
  ) then
    return false;
  end if;
  delete from public.user_student_pair usp
  where usp.student_id = p_student_id and usp.user_id = p_parent_user_id
  returning usp.created_at into _linked_at;
  if not found then
    return false;
  end if;
  insert into public.parent_link_revocation (student_id, parent_user_id, linked_at, revoked_by_user_id)
  values (p_student_id, p_parent_user_id, _linked_at, p_actor_user_id);
  return true;
end;
$$;

-- Admin: issue a fresh code for one student or teacher. Returns the new code, for the staff issuing
-- screen only (hard rule 4). Existing links are untouched. Rotation stops future use of the old code.
create or replace function public.admin_rotate_link_code(p_actor_user_id bigint, p_kind text, p_id bigint)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  _code text;
  _attempt integer := 0;
begin
  if p_kind not in ('student', 'teacher') then
    raise exception 'Unknown kind' using errcode = '22023';
  end if;
  loop
    _attempt := _attempt + 1;
    _code := public.generate_link_code();
    begin
      if p_kind = 'student' then
        update public.student s set link_code = _code
        where s.id = p_id and public.is_admin_of_school(p_actor_user_id, s.school_id);
      else
        update public.teacher t set link_code = _code
        where t.id = p_id and public.is_admin_of_school(p_actor_user_id, t.school_id);
      end if;
      if not found then
        raise exception 'Not authorized' using errcode = '42501';
      end if;
      return _code;
    exception when unique_violation then
      if _attempt >= 5 then raise; end if;
    end;
  end loop;
end;
$$;

-- Student's own screen: "A parent account was linked on <date>" (§10.11). Dates only.
create or replace function public.own_parent_link_dates(p_actor_user_id bigint)
returns table (linked_on date)
language sql
stable
security definer
set search_path = ''
as $$
  select usp.created_at::date
  from public.user_student_pair usp
  join public.student s on s.id = usp.student_id
  where s."linkedUser" = p_actor_user_id
  order by usp.created_at;
$$;

