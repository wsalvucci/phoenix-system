// Writes .env.test.local from the LOCAL Supabase stack (`supabase status`). Never touches .env.local.
// Refuses to write anything unless the stack answers on localhost / 127.0.0.1.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

let raw;
try {
  raw = execFileSync("supabase", ["status", "-o", "env"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
} catch (e) {
  console.error("The local Supabase stack is not running. Start it with: supabase start");
  console.error(String(e.stderr ?? e.message).trim());
  process.exit(1);
}

const status = {};
for (const line of raw.split("\n")) {
  const m = line.match(/^([A-Z_]+)="?(.*?)"?$/);
  if (m) status[m[1]] = m[2];
}

const api = status.API_URL;
const db = status.DB_URL;
const local = (u) => {
  try {
    return ["127.0.0.1", "localhost"].includes(new URL(u).hostname);
  } catch {
    return false;
  }
};
if (!api || !local(api) || !db || !local(db)) {
  console.error(`Refusing to continue: the Supabase target is not local (API_URL=${api}, DB_URL=${db}).`);
  process.exit(1);
}
for (const key of ["ANON_KEY", "SERVICE_ROLE_KEY"]) {
  if (!status[key]) {
    console.error(`supabase status did not report ${key}.`);
    process.exit(1);
  }
}

const lines = [
  "# Generated by scripts/test-env.mjs from the LOCAL stack. Gitignored. Do not put production keys here.",
  `NEXT_PUBLIC_SUPABASE_URL=${api}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
  `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
  `SUPABASE_DB_URL=${db}`,
  "LINK_RATE_LIMIT_SECRET=local-test-secret-0123456789abcdef0123456789abcdef",
  "E2E_PASSWORD=Passw0rd!test",
  "",
];
writeFileSync(resolve(root, ".env.test.local"), lines.join("\n"));
console.log(`Wrote .env.test.local for ${api}`);
