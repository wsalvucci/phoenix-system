CREATE POLICY "Admins Can Manage Teacher Student Group Pairs in School" ON public.teacher_student_group_pair AS PERMISSIVE FOR ALL TO public
  USING ((EXISTS ( SELECT 1
   FROM (((("user"
     JOIN admin ON (("user".admin_id = admin.id)))
     JOIN admin_school_pair ON ((admin.id = admin_school_pair.admin_id)))
     JOIN school ON ((admin_school_pair.school_id = school.id)))
     JOIN teacher ON ((school.id = teacher.school_id)))
  WHERE (("user".supabase_id = auth.uid()) AND (teacher.id = teacher_student_group_pair.teacher_id)))));
CREATE POLICY "Teachers Can See Group Pairs They're Assigned" ON public.teacher_student_group_pair AS PERMISSIVE FOR SELECT TO public
  USING ((EXISTS ( SELECT 1
   FROM "user"
  WHERE (("user".supabase_id = auth.uid()) AND ("user".teacher_id = teacher_student_group_pair.teacher_id)))));

